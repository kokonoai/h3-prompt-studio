const reverse = new Map<string, string>();
for (const [english, translations] of Object.entries(PHRASES)) {
  reverse.set(english, english);
  for (const value of Object.values(translations)) reverse.set(value, english);
}

function dynamic(text: string, language: UiLanguage): string | null {
  const choose = (zh: string, tw: string, ja: string, en = text) => language === "zh-CN" ? zh : language === "zh-TW" ? tw : language === "ja" ? ja : en;
  let match = text.match(/^(?:You play |你扮演 )(.+)$/);
  if (match) return choose(`你扮演 ${match[1]}`, `你扮演 ${match[1]}`, `${match[1]}としてプレイ`, `You play ${match[1]}`);
  match = text.match(/^(.+)としてプレイ$/);
  if (match) return choose(`你扮演 ${match[1]}`, `你扮演 ${match[1]}`, `${match[1]}としてプレイ`, `You play ${match[1]}`);
  match = text.match(/^(?:Shot|镜头|鏡頭|ショット)\s*(\d+)(.*)$/i);
  if (match) return choose(`镜头 ${match[1]}${match[2]}`, `鏡頭 ${match[1]}${match[2]}`, `ショット ${match[1]}${match[2]}`, `Shot ${match[1]}${match[2]}`);
  match = text.match(/^(\d+)\s*(?:seconds?|秒)$/i);
  if (match) return choose(`${match[1]} 秒`, `${match[1]} 秒`, `${match[1]}秒`, `${match[1]} seconds`);
  match = text.match(/^(\d+)\s*(?:steps?|步|ステップ)$/i);
  if (match) return choose(`${match[1]} 步`, `${match[1]} 步`, `${match[1]}ステップ`, `${match[1]} steps`);
  match = text.match(/^(?:Take|版本|テイク)\s*(\d+)$/i);
  if (match) return choose(`版本 ${match[1]}`, `版本 ${match[1]}`, `テイク ${match[1]}`, `Take ${match[1]}`);
  match = text.match(/^(?:Checks|检查|檢查|チェック)\s*\((\d+)\)$/i);
  if (match) return choose(`检查 (${match[1]})`, `檢查 (${match[1]})`, `チェック (${match[1]})`, `Checks (${match[1]})`);
  return null;
}

function translate(text: string, language: UiLanguage) {
  const english = reverse.get(text) || text;
  const value = PHRASES[english];
  if (value) return language === "en" ? english : value[language];
  return dynamic(text, language) || text;
}

export function useLegacyUiTranslation(ref: RefObject<HTMLElement | null>, language: UiLanguage) {
  useEffect(() => {
    const root = ref.current;
    if (!root) return;
    let frame = 0;
    const apply = () => {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node: Node | null;
      while ((node = walker.nextNode())) {
        const parent = node.parentElement;
        if (!parent || parent.closest("script,style") || parent.matches("textarea")) continue;
        const raw = node.nodeValue || "";
        const compact = raw.trim();
        if (!compact) continue;
        const next = translate(compact, language);
        if (next !== compact) node.nodeValue = raw.replace(compact, next);
      }
      for (const element of root.querySelectorAll<HTMLElement>("[placeholder],[title],[aria-label]")) {
        for (const name of ["placeholder", "title", "aria-label"]) {
          const raw = element.getAttribute(name);
          if (!raw) continue;
          const next = translate(raw.trim(), language);
          if (next !== raw.trim()) element.setAttribute(name, next);
        }
      }
    };
    const observer = new MutationObserver(() => {
      cancelAnimationFrame(frame);
      frame = requestAnimationFrame(() => { observer.disconnect(); apply(); observer.observe(root, {subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:["placeholder","title","aria-label"]}); });
    });
    apply();
    observer.observe(root, {subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:["placeholder","title","aria-label"]});
    return () => { cancelAnimationFrame(frame); observer.disconnect(); };
  }, [ref, language]);
}
